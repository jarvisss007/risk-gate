"""Build a SYNTHETIC estate in examples/estate/: fake desks, fake rows, a fake equity curve, a fake reference index.

Nothing here is an account figure. The curve is in index points (100 at the start) and is shaped so that one pass of
the layer shows: a budget key set and cleared, a kill-line trip, a brake and a regime key that would fire but are not
enforced, and a kill-line clear by the full re-entry rule.

  python examples/make_estate.py            # writes examples/estate/{equity_curve.csv,index.csv,prices.csv,risk.json}
"""
import csv
import json
from pathlib import Path

import numpy as np

import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from riskgate.calendar import Calendar  # noqa: E402

CAL = Calendar()
EST = ROOT / 'examples' / 'estate'
FIRST, LAST = '2026-09-01', '2026-12-04'          # the layer's sessions
INDEX_FROM = '2025-09-01'                          # the index needs 200+ closes before FIRST for its SMA
TICKERS = ['AAA', 'BBB', 'CCC', 'DDD', 'EEE', 'FFF']
DESKS = ['insider desk', 'fundamentals desk', 'pattern desk', 'options arm A', 'options arm B']


def sessions(a, b):
    out, d = [], CAL.roll_to_session(a)
    while d.isoformat() <= b:
        out.append(d.isoformat())
        d = CAL.next_session(d)
    return out


def equity_path(days, seed=7):
    """Rise to a high in late September, a fall through mid-October that crosses the 10% line (with one -3.4% day),
    a slow climb back above the line, then a gentle rise. Index points, 100 at the start."""
    rng = np.random.default_rng(seed)
    n = len(days)
    drift = np.zeros(n)
    for i, d in enumerate(days):
        if d <= '2026-09-26':
            drift[i] = 0.0040
        elif d <= '2026-10-14':
            drift[i] = -0.0075
        elif d <= '2026-10-23':
            drift[i] = -0.0015
        elif d <= '2026-11-13':
            drift[i] = 0.0055
        else:
            drift[i] = 0.0020
    noise = rng.normal(0, 0.004, n)
    r = drift + noise
    r[days.index('2026-10-14')] = -0.034                        # the worst day: the brake would fire here
    eq = 100 * np.cumprod(1 + r)
    return [round(float(x), 4) for x in eq]


def index_path(days, seed=11):
    """A reference index: up for a year, a correction in October that puts the month-end close below the 200-day SMA,
    recovery through November."""
    rng = np.random.default_rng(seed)
    n = len(days)
    drift = np.zeros(n)
    for i, d in enumerate(days):
        if d < '2026-09-20':
            drift[i] = 0.0006
        elif d <= '2026-10-30':
            drift[i] = -0.0040
        elif d <= '2026-11-20':
            drift[i] = 0.0065
        else:
            drift[i] = 0.0015
    r = drift + rng.normal(0, 0.006, n)
    px = 1000 * np.cumprod(1 + r)
    return [round(float(x), 2) for x in px]


def prices(days, seed=3):
    rng = np.random.default_rng(seed)
    out = {}
    for k, t in enumerate(TICKERS):
        r = rng.normal(0.0002 * (k - 2), 0.02, len(days))
        out[t] = [round(float(x), 3) for x in 50 * (k + 1) * np.cumprod(1 + r)]
    return out


def risk_for(day):
    """Percent of equity at risk per desk / arm and per sector at that close. One arm goes over its 8% ceiling for
    four sessions in early October; one sector is over 25% for two sessions; one session's sector reading is
    UNCLASSIFIED (coverage too low to judge)."""
    desks = {'insider desk': 5.5, 'fundamentals desk': 4.0, 'pattern desk': 1.5, 'options arm A': 6.0, 'options arm B': 3.0}
    sectors = {'semiconductors': 14.0, 'software': 9.0, 'retail': 4.0}
    if '2026-10-06' <= day <= '2026-10-09':
        desks['options arm A'] = 9.4
    if '2026-10-07' <= day <= '2026-10-08':
        sectors['semiconductors'] = 27.5
    if day == '2026-10-09':
        sectors = None
    return {'desks': desks, 'sectors': sectors}


def make():
    EST.mkdir(parents=True, exist_ok=True)
    days = sessions(FIRST, LAST)
    idays = sessions(INDEX_FROM, LAST)
    with open(EST / 'equity_curve.csv', 'w', newline='') as fh:
        w = csv.writer(fh); w.writerow(['date', 'equity'])
        w.writerows(zip(days, equity_path(days)))
    with open(EST / 'index.csv', 'w', newline='') as fh:
        w = csv.writer(fh); w.writerow(['date', 'close'])
        w.writerows(zip(idays, index_path(idays)))
    p = prices(days)
    with open(EST / 'prices.csv', 'w', newline='') as fh:
        w = csv.writer(fh); w.writerow(['date'] + TICKERS)
        for i, d in enumerate(days):
            w.writerow([d] + [p[t][i] for t in TICKERS])
    (EST / 'risk.json').write_text(json.dumps({d: risk_for(d) for d in days}, indent=1) + '\n')
    (EST / 'README.md').write_text(
        '# Synthetic estate\n\nEverything in this folder is generated by `examples/make_estate.py` with fixed seeds: a fake '
        'equity curve in index points, a fake reference index, six fake tickers, and per-session at-risk shares for five fake '
        'desks. No figure here comes from any real account.\n\n`generated/` (git-ignored) holds the halt file, books and refusal '
        'records that `examples/demo.py` writes.\n')
    return days


if __name__ == '__main__':
    d = make()
    print(f'wrote {EST.relative_to(ROOT)}: {len(d)} sessions {d[0]}..{d[-1]}, {len(TICKERS)} tickers, {len(DESKS)} desks')
